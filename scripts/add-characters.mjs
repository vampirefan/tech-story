const files = ['src/data/nodes-ancient.ts', 'src/data/nodes-middle.ts', 'src/data/nodes-modern.ts', 'src/data/nodes-now.ts']
let filled = 0
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split('\n')
  let cur = null
  let pending = null
  for (let i = 0; i < lines.length; i++) {
    const idm = lines[i].match(/^\s{4}id: '([a-z0-9_]+)'/)
    if (idm) { cur = idm[1]; pending = cur in CHARS ? cur : null }
    if (pending && /^ {4}characters: \[\],$/.test(lines[i])) {
      const body = CHARS[pending].map(c =>
        `      { name: '${c.name}', role: '${c.role}', note: '${c.note}' }`).join(',\n')
      lines[i] = `    characters: [\n${body}\n    ],`
      filled++
      pending = null
    }
  }
  writeFileSync(f, lines.join('\n'))
}
console.log('填充人物小传的节点数:', filled, '/', Object.keys(CHARS).length)
